block("Block 7 — 先行モデル：この描像は既に実験で検証済みの形で存在する")
# ----------------------------------------------------------------------
# Heitler の空気シャワー・トイモデル（電磁カスケード）
#   各段で粒子数が2倍、1粒子あたりのエネルギーは半分。
#   E/粒子 が臨界エネルギー E_c を下回った段で増殖停止。
#   N_max = E0/E_c ,  X_max = lambda * ln(E0/E_c)/ln2
def heitler(E0_eV, Ec_eV, lam_g_cm2=37.0):
    n = math.log(E0_eV / Ec_eV) / math.log(2)
    return n, 2 ** n, lam_g_cm2 * n

Ec_air = 85e6           # 空気中の臨界エネルギー ~85 MeV
for E0_eV, lab in [(1e15, "1 PeV"), (1e18, "1 EeV"), (1e20, "100 EeV")]:
    n, N, X = heitler(E0_eV, Ec_air)
    print("  E0=%-8s : 段数 n=%5.1f, 最大粒子数 N_max=%.3g, X_max≈%.0f g/cm^2" %
          (lab, n, N, X))
    assert abs(N - E0_eV / Ec_air) / (E0_eV / Ec_air) < 1e-9   # N_max = E0/Ec
# 放射長 lambda=37 g/cm^2 は偶然にも 37 だが無関係（空気の放射長 36.62）
print("""
  Heitler 模型（1954, 'The Quantum Theory of Radiation'）の結論は
  本人の問いへの答えそのもの:
    **「分岐は止まらない。止まるのは1個あたりのエネルギーが閾値に達したとき。
      粒子数は有限（N_max = E0/E_c）で、到達までの段数は log。」**
  これは宇宙線空気シャワーで実測され、X_max の伸び（elongation rate）まで
  定量的に合う。

  同型の第2例: インフレーション後の preheating
  （Kofman–Linde–Starobinsky 1994, PRL 73, 3195）。
  パラメトリック共鳴で粒子数が指数的に増え、インフラトンのエネルギーが
  尽きた時点で止まる。宇宙創成論としてはこちらが直接の対応物。

  → 本人の直観「指数的に生まれ、粒子になって止まる」は **物理として正しい**。
    ただし新規性は『指数増殖する』側にはない（1954年に確立）。
    新規性が残りうるのは『e_min を幾何から決める』側のみ。""")

# 余談: 放射長との数値一致は偶然であることを明示
assert abs(36.62 - 37) < 0.5
print("  （注: 空気の放射長 36.62 g/cm^2 と 37 の一致は完全な偶然。単位依存量。）")

