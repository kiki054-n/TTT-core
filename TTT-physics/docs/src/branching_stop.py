block("Block 6 — 停止機構 候補C：保存量＋下限（これだけが本当に止める）")
# ----------------------------------------------------------------------
# 総量 E0 が保存され、各誕生で分割される。k 世代で N=3^k 個、1個あたり e=E0/3^k。
# e が下限 e_min を下回れなくなった時点で誕生が止まる。
def saturate(E0, emin):
    k = 0
    while E0 / 3 ** k > emin:
        k += 1
    return k, 3 ** k, E0 / 3 ** (k - 1)

for E0, emin, lab in [(1.0, 1e-20, "E0/emin = 1e20"),
                      (1.0, 1e-40, "E0/emin = 1e40"),
                      (1.0, 1e-80, "E0/emin = 1e80")]:
    k, N, elast = saturate(E0, emin)
    kth = math.log(E0 / emin) / math.log(3)
    print("  %-18s → 停止世代 k = %3d（理論値 %.2f）, 個数 N = 3^k ≈ %.3g" %
          (lab, k, kth, N))
    assert abs(k - kth) <= 1
    assert N >= E0 / emin > N / 3
print("""
  閉形式:  k_stop = log_3(E0/e_min) ,  N_max = E0/e_min
  → **有限で止まる。しかも止まる個数は E0/e_min だけで決まり、
    分岐の枝数（2つか3つか）は k_stop の対数係数にしか効かない。**

  重要（判断点に直結）:
    N_max は無次元比なのでこれ自体は良い。しかし e_min は次元を持つ定数で、
    「1個体がこれ以上分割できない最小の量」とは、周期 T を持つ運動に対して
    E*T = 一定 の下限を置くこと、すなわち **作用の量子 = hbar の導入**である。
    9/13 の3本のノート（unit_closure / T_powers / constants_null）が
    いずれも指した「T^4 の空席」と、ここは同じ穴。
    **『いつ止まるか』を答えた瞬間に hbar が入る。**""")

# 次元解析でそれを機械確認
E, T = sp.symbols('E T', positive=True)
# [E]=M L^2 T^-2, 周期 [T]=T。E*T の次元 = M L^2 T^-1 = 作用
M_, L_, T_ = sp.symbols('M L Tdim', positive=True)
dimE = M_ * L_ ** 2 * T_ ** -2
dimAction = sp.simplify(dimE * T_)
assert sp.simplify(dimAction - M_ * L_ ** 2 / T_) == 0
print("  次元確認: [E]*[T] = M L^2 T^-1 = [作用] = [hbar]  ✓")

