block("Block 1 — 誕生則を漸化式に落とす（0,2,6,18,54,162 の再現）")
# ----------------------------------------------------------------------
# 規則: 各時刻に、存在する全個体（最初の1個体を含む）がそれぞれ2つ産む。
#       親は消えない。
#   N_total(0) = 1
#   N_new(k)   = 2 * N_total(k-1)
#   N_total(k) = N_total(k-1) + N_new(k) = 3 * N_total(k-1)
tot = [1]
new = [0]
for k in range(1, 13):
    n = 2 * tot[-1]
    new.append(n)
    tot.append(tot[-1] + n)

print("k :  新規誕生 N_new(k)      累積 N_total(k)")
for k in range(0, 9):
    print("%2d : %14d %20d" % (k, new[k], tot[k]))

assert new[:6] == [0, 2, 6, 18, 54, 162], new[:6]          # 記録の誕生則と一致
assert tot[:6] == [1, 3, 9, 27, 81, 243], tot[:6]
for k in range(1, 13):
    assert tot[k] == 3 ** k
    assert new[k] == 2 * 3 ** (k - 1)
    assert sum(new[:k + 1]) == 3 ** k - 1                   # 累積誕生数（根を除く）
print("\n閉形式（証明済み）:  N_total(k) = 3^k ,  N_new(k) = 2*3^(k-1)")
print("記録の『各世代3倍』は、この規則の恒等的な帰結であり追加仮定ではない。")

