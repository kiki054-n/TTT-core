block("Block 3 — 停止機構 候補A：出産回数を有限にする（→ 止まらない）")
# ----------------------------------------------------------------------
# 「各個体は生涯に Fmax 回だけ（毎回2つ）産み、その後は不活性」
# new(k) = 2 * sum_{j=1..Fmax} new(k-j)   （根を new(0)=1 とする）
print("  Fmax : 増殖率 x（特性方程式 x^F = 2(x^{F-1}+...+1) の最大実根）")
prev = None
for Fmax in [1, 2, 3, 5, 10, 30]:
    x = sp.symbols('x', positive=True)
    poly = x ** Fmax - 2 * sum(x ** i for i in range(Fmax))
    r = max([sp.nsimplify(v) for v in sp.nroots(sp.Poly(poly, x))
             if abs(sp.im(v)) < 1e-12 and sp.re(v) > 0], key=lambda v: sp.re(v))
    rv = float(sp.re(r))
    # 数値シミュレーションで確認
    seq = [1] + [0] * 40
    for k in range(1, 41):
        seq[k] = 2 * sum(seq[max(0, k - Fmax):k])
    ratio = seq[40] / seq[39]
    print("   %3d  : x = %.6f   （数値比 %.6f）" % (Fmax, rv, ratio))
    assert abs(rv - ratio) < 1e-6, (rv, ratio)
    assert rv > 1.9999
    if prev is not None:
        assert rv > prev            # Fmax とともに単調増加、上限3
    prev = rv
assert rv < 3 + 1e-12          # 厳密には x<3、Fmax→∞ で 3 に下から収束（浮動小数の丸め込み）
print("""
  → 出産回数をいくら制限しても x >= 2 で、依然として指数増殖。
    Fmax=1（一度だけ産んで不活性）でも 2^k。
    **「有限の出産数」は停止機構にならない。** 減速するだけ。""")

