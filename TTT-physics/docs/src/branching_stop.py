block("Block 5 — 帰無対照：『162 − 125 = 37』はどれくらい珍しいか")
# ----------------------------------------------------------------------
# 語彙（TTT 内で既に使われている整数）
vocab = {4, 5, 7, 12, 17, 20, 24, 30, 35, 37, 48, 60, 108, 120, 125, 137}

print("  (i) 規則を ×3 に固定したまま、底 a だけ動かす（初回超過のみ）")
print("      a :   a^3    初回 N_new   超過 e    e/a^3   語彙入り")
small = 0
for a in range(2, 13):
    C_ = a ** 3
    kk = next(k for k in range(1, 30) if 2 * 3 ** (k - 1) > C_)
    e = 2 * 3 ** (kk - 1) - C_
    if e < C_:
        small += 1
    print("     %2d : %6d %10d %8d %8.3f    %s"
          % (a, C_, 2 * 3 ** (kk - 1), e, e / C_, "○" if e in vocab else ""))
assert small == 4          # 「超過が容量未満」に収まるのは a∈{3,5,8,12} の4つだけ
print("      → 『超過が容量未満に収まる』のは 11 個中 4 個。a=5 はその1つ。")
print("      → e/a^3 は [0,2) に散らばり、a=5 の 0.296 は特に小さい側ではない。")

print("\n  (ii) 規則そのものを動かす（分岐数 b、容量指数 d も自由にする）")
hits, total_pairs = [], 0
for b in (1, 2, 3, 4):                       # 親が産む数 → 倍率 (1+b)
    for d in (2, 3):                         # 容量 a^d
        for a in range(2, 13):
            C_ = a ** d
            try:
                kk = next(k for k in range(1, 40)
                          if b * (1 + b) ** (k - 1) > C_)
            except StopIteration:
                continue
            e = b * (1 + b) ** (kk - 1) - C_
            if 0 < e < C_:
                total_pairs += 1
                if e in vocab:
                    hits.append((b, d, a, kk, e))
print("      族: 『b*(1+b)^(k-1) − a^d』 b=1..4, d=2..3, a=2..12（初回超過）")
print("      該当 %d 件、うち超過が TTT 語彙(%d個)に入るもの %d 件"
      % (total_pairs, len(vocab), len(hits)))
for h in sorted(hits):
    print("        b=%d d=%d a=%2d k=%2d → 超過 %d" % h)
dens = len(hits) / total_pairs
print("      → 命中密度 %.1f%%" % (100 * dens))
assert any(h[:3] == (2, 3, 5) for h in hits)
assert total_pairs >= 20
print("""
  比較: 9/13 の帰無対照では 108 のとき 1.10%、137 のとき 5.45%、
        1836 のとき 8.5%。今回はそれらより緩い。
  **『37 が出た』だけでは選別力がない。** 選別力を持たせる唯一の道は、
  b=2 と a=5 と d=3 と「世代ごとに数える」を、
  当てはめではなく規則の側から強制すること。
  なお有利な点も1つある: 37 は *整数の差* として出るので、
  137 や 1836 のときのような「4桁合わせて残り7桁を外す」型の失敗は
  この標的には起きない。落ちるとすれば選別力のなさの方である。""")

